def parse_historical_yield_table(table_text: str, column_name: str) -> pd.DataFrame:
    """Convert ``year value...`` rows into a monthly, date-indexed yield series.

    The five Bank of Canada historical PDFs use the same twelve-column layout.
    Missing cells are represented by ``-`` or ``**`` and become NaN. The parser
    expects one year followed by up to twelve monthly values, with blank cells
    allowed where the source table begins part-way through a year.
    """
    rows = []
    for raw_line in table_text.strip().splitlines():
        parts = raw_line.split()
        if not parts:
            continue

        year = int(parts[0])
        values = [np.nan if value.lower() in {"-", "**", "nan"} else float(value) for value in parts[1:]]
        values.extend([np.nan] * (12 - len(values)))
        if len(values) != 12:
            raise ValueError(f"Historical yield row {year} must contain 12 monthly values")

        for month, value in enumerate(values, start=1):
            rows.append((pd.Timestamp(year=year, month=month, day=1), value))

    return pd.DataFrame(rows, columns=["date", column_name]).set_index("date")


